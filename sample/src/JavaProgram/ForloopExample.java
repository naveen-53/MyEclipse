package JavaProgram;

public class ForloopExample {
	
	public static void main(String args[]) {
		
		// for(initialization;condition;increment/decrement)
		int i;
		for(i=0;i<5;i++) {
			System.out.println("Naveen");
		}
		System.out.println("-------------------------------------------");
		System.out.println();
		
		String chocolates[]= {"Dairy milk","KitKat","5 star","perk","munch","snickers"};
		
		for(String a:chocolates) {
			System.out.println(a);
		
		}
		
	}
	

}
